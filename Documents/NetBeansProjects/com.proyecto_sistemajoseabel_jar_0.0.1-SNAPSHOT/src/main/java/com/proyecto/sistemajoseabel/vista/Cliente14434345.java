private void cargarClientes() {
        List<Produccion> producciones = serviciopro.obtenerTodasLasProducciones();
        System.out.println("Clientes encontrados: " + producciones.size());

        DefaultTableModel modelo = (DefaultTableModel) tablaclientes.getModel();
        modelo.setRowCount(0); // Limpia tabla

        for (Produccion produccion : producciones) {
            modelo.addRow(new Object[]{
                produccion.getIdProduccion(),
                produccion.getNombre(),
                produccion.getFechaInicio(),
                produccion.getFechaFin(),
                produccion.getEstado(),
                produccion.getDetalles(),
                produccion.getPedido()
            });
        }
    }



