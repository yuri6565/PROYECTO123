    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
    int filaSeleccionada = tablaclientes.getSelectedRow();

        if (filaSeleccionada != -1) {
            int confirmacion = JOptionPane.showConfirmDialog(this, "¿Estás seguro de eliminar este cliente?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);

            if (confirmacion == JOptionPane.YES_OPTION) {
                int idProduccion = (int) tablaclientes.getValueAt(filaSeleccionada, 0);
                serviciopro.eliminar(idProduccion);
                cargarClientes(); // Recargar la lista de clientes
                JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Selecciona un cliente para eliminar.");
        }
          
    
    }//GEN-LAST:event_btnEliminarActionPerformed

