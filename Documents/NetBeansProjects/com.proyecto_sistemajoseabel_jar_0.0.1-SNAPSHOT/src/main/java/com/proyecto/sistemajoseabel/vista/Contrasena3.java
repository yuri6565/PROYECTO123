    private void rSMaterialButtonRectangle2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rSMaterialButtonRectangle2ActionPerformed
  String codigoIngresado = txtcodigo.getText().trim();

    if (codigoIngresado.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor completa el campo del código.", "Campo vacío", JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean esValido = Serviciocorreo.verificarCodigo(correoIngresado, codigoIngresado);


    if (esValido) {
        JOptionPane.showMessageDialog(this, "Código verificado correctamente. Puedes continuar.");
System.out.println("Abrir ventana de cambio de contraseña");
NuevaContrasena cambiar = context.getBean(NuevaContrasena.class);
cambiar.setCorreoIngresado(correoIngresado); // asegurate de tener este método
cambiar.setVisible(true);

    } else {
        JOptionPane.showMessageDialog(this, "El código ingresado es incorrecto. Intenta nuevamente.", "Código incorrecto", JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_rSMaterialButtonRectangle2ActionPerformed

