    private void jLabel6MousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel6MousePressed


  jLabel6.setEnabled(false);
    new Timer(30000, e -> jLabel6.setEnabled(true)).start();

    try {
        boolean esValido = Serviciocorreo.enviarCodigoRecuperacion(correoIngresado); // <- ¡Ya funciona!
        if (esValido) {
            JOptionPane.showMessageDialog(this, "Código reenviado correctamente a tu correo.", "Código reenviado", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Ocurrió un error al reenviar el código. Intenta nuevamente.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Error al enviar el código: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        ex.printStackTrace();
    }



  

    }//GEN-LAST:event_jLabel6MousePressed

